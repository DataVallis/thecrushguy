#!/usr/bin/env bash
# Writes the nginx snippets that make the origin trust Cloudflare (owner runs this ON THE SERVER; idempotent).
#   sudo ops/nginx/cloudflare-ips.sh --dry-run   # print what would be written
#   sudo ops/nginx/cloudflare-ips.sh             # write files, test nginx, reload
# Produces:
#   /etc/nginx/snippets/cloudflare-realip.conf  — real client IP from CF-Connecting-IP, trusted only from Cloudflare ranges
#   /etc/nginx/conf.d/cloudflare-geo.conf       — $from_cloudflare = 1 when the TCP peer is Cloudflare (http context)
# Only server blocks that `include` the snippets are affected — other sites on this shared host are not.
# Re-run monthly (cron) or when Cloudflare publishes new ranges: https://www.cloudflare.com/ips/
set -euo pipefail
DRY=0; [[ "${1:-}" == "--dry-run" ]] && DRY=1
v4=$(curl -fsS https://www.cloudflare.com/ips-v4)
v6=$(curl -fsS https://www.cloudflare.com/ips-v6)
ranges=$(printf '%s\n%s\n' "$v4" "$v6" | grep -E '^[0-9a-fA-F:.]+/[0-9]+$')
[[ $(wc -l <<<"$ranges") -ge 10 ]] || { echo "unexpected Cloudflare range list, aborting" >&2; exit 1; }

realip="# Generated by ops/nginx/cloudflare-ips.sh — do not edit.
$(sed 's/^/set_real_ip_from /; s/$/;/' <<<"$ranges")
real_ip_header CF-Connecting-IP;"
geo="# Generated by ops/nginx/cloudflare-ips.sh — do not edit.
geo \$realip_remote_addr \$from_cloudflare {
    default 0;
$(sed 's/^/    /; s/$/ 1;/' <<<"$ranges")
}"

if [[ $DRY == 1 ]]; then
  printf '=== /etc/nginx/snippets/cloudflare-realip.conf\n%s\n=== /etc/nginx/conf.d/cloudflare-geo.conf\n%s\n' "$realip" "$geo"
  exit 0
fi
install -d /etc/nginx/snippets
printf '%s\n' "$realip" > /etc/nginx/snippets/cloudflare-realip.conf
printf '%s\n' "$geo" > /etc/nginx/conf.d/cloudflare-geo.conf
nginx -t && systemctl reload nginx && echo "Cloudflare snippets updated ($(wc -l <<<"$ranges") ranges)"
